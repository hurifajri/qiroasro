import type { Metadata, Viewport } from 'next';
import { Google_Sans_Flex } from 'next/font/google';
import '@/styles/global.css';
import { ReactQueryDevtools } from '@tanstack/react-query-devtools';
import { NextIntlClientProvider } from 'next-intl';
import { LocaleThemeSelector } from '@/components/locale-theme-selector';
import { cn } from '@/lib/utils';
import { GlobalStoreProvider } from '@/providers/global-store';
import { QueryClientProvider } from '@/providers/query-client';
import { getPersistedGlobalStore } from '@/stores/global';

const googleSansFlex = Google_Sans_Flex({
  variable: '--font-google-sans-flex',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
};

export default async function RootLayout({
  children,
}: React.PropsWithChildren) {
  const persistedStore = await getPersistedGlobalStore();
  const { locale, theme } = persistedStore;

  return (
    <html
      lang={locale}
      className={theme}
      style={{ colorScheme: theme }}
      suppressHydrationWarning
    >
      <body className={cn('font-sans antialiased', googleSansFlex.variable)}>
        <QueryClientProvider>
          <GlobalStoreProvider initialState={persistedStore}>
            <NextIntlClientProvider>
              {children}
              <LocaleThemeSelector locale={locale} theme={theme} />
            </NextIntlClientProvider>
          </GlobalStoreProvider>
          {process.env.NODE_ENV === 'development' && (
            <ReactQueryDevtools
              initialIsOpen={false}
              buttonPosition="top-left"
              position="right"
            />
          )}
        </QueryClientProvider>
      </body>
    </html>
  );
}
